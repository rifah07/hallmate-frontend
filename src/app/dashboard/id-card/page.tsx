'use client';

import { Avatar } from '@/components/Avatar';
import { Loading } from '@/components/Loading';
import { formatDate } from '@/lib/format';
import { site } from '@/lib/site';
import { useData } from '@/lib/use-data';

type Card = {
  name: string;
  universityId: string;
  department: string | null;
  session: string | null;
  bloodGroup: string | null;
  photo: string | null;
  room: string | null;
  validUntil: string;
  qrSvg: string;
};

export default function IdCardPage() {
  const { data: card, error } = useData<Card>('/id-card/me');

  return (
    <>
      <header className="dash-head">
        <span className="kicker">Show this at the gate</span>
        <h1>Hall ID card</h1>
        <p className="muted">The guard scans the code to see your photo and room. A cancelled seat stops the card at once.</p>
      </header>
      {!card ? (
        <Loading error={error} />
      ) : (
        <article className="id-card" aria-label="Hall ID card">
          <header>
            <span className="brand-mark" aria-hidden="true" />
            <div>
              <b>{site.name}</b>
              <span>{site.university}</span>
            </div>
          </header>
          <div className="id-card-body">
            <Avatar src={card.photo} name={card.name} size={96} />
            <dl>
              <dt>Name</dt>
              <dd>{card.name}</dd>
              <dt>University ID</dt>
              <dd>{card.universityId}</dd>
              {card.department && (
                <>
                  <dt>Department</dt>
                  <dd>{card.department}</dd>
                </>
              )}
              <dt>Room</dt>
              <dd>{card.room ?? '—'}</dd>
              {card.bloodGroup && (
                <>
                  <dt>Blood group</dt>
                  <dd>{card.bloodGroup.replace('_POSITIVE', '+').replace('_NEGATIVE', '−')}</dd>
                </>
              )}
            </dl>
            {/* An <img> of the SVG, never injected markup */}
            {/* eslint-disable-next-line @next/next/no-img-element -- data URI generated by our API */}
            <img
              className="id-qr"
              src={`data:image/svg+xml;charset=utf-8,${encodeURIComponent(card.qrSvg)}`}
              alt="QR code for the gate"
              width={148}
              height={148}
            />
          </div>
          <footer>Valid until {formatDate(card.validUntil)}</footer>
        </article>
      )}
    </>
  );
}
